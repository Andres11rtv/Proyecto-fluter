class Museo {
  final int id;
  final String nombre;
  final String descripcion;
  final double latitud;
  final double longitud;
  final String sitioWeb;

  Museo({
    required this.id,
    required this.nombre,
    required this.descripcion,
    required this.latitud,
    required this.longitud,
    required this.sitioWeb,
  });
}